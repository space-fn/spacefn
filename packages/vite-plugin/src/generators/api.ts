import { generators } from "../generators.js";
import { buildRoutePath, parseMethodPostfix } from "../utils.js";

export function apiGenerator() {
	return generators({
		watch: "src/api/**/*.ts",
		output: ".space/api.ts",
		generate(files) {
			const routes = files.map((file) => {
				const method = parseMethodPostfix(file);
				const cleanFile = method ? file.replace(/\.\w+\.ts$/, ".ts") : file;
				return {
					routePath: buildRoutePath(cleanFile, "src/api"),
					method: method ?? "all",
					importPath: file.replace(/\.ts$/, ""),
				};
			});

			const imports = routes
				.map((r, i) => `import route_${i} from "../${r.importPath}"`)
				.join("\n");

			const registrations = routes
				.map((r, i) => `api.${r.method}("${r.routePath}", route_${i})`)
				.join(";\n");

			return [
				`// @ts-nocheck`,
				`// Auto-generated by spaceGenerators — DO NOT EDIT`,
				`import { Hono } from "hono"`,
				imports,
				"",
				`const api = new Hono()`,
				registrations,
				"",
				`export default api`,
			].join("\n");
		},
	});
}
