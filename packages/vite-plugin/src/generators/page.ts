import { generators } from "../generators.js";
import { buildRoutePath } from "../utils.js";

export function pageGenerator() {
	return generators({
		watch: "src/pages/**/*.ts",
		output: ".space/pages.ts",
		generate(files) {
			const routes = files.map((file) => ({
				routePath: buildRoutePath(file, "src/pages"),
				importPath: file.replace(/\.ts$/, ""),
			}));

			const imports = routes
				.map((r, i) => `import * as page_${i} from "../${r.importPath}"`)
				.join("\n");

			const getRoutes = routes
				.map(
					(r, i) => `
pages.get("${r.routePath}", async (c) => {
  const data = page_${i}.loader ? await page_${i}.loader(c) : {}
  return page_${i}.default(data)
})`,
				)
				.join("");

			const postRoutes = routes
				.map(
					(r, i) => `
pages.post("${r.routePath}", async (c) => {
  const action = c.req.query("_action")
  if (action && page_${i}.actions?.[action]?.resolver) {
    return page_${i}.actions[action].resolver(c)
  }
  return c.notFound()
})`,
				)
				.join("");

			return [
				`// @ts-nocheck`,
				`// Auto-generated by spaceGenerators — DO NOT EDIT`,
				`import { Hono } from "hono"`,
				imports,
				"",
				`const pages = new Hono()`,
				getRoutes,
				postRoutes,
				"",
				`export default pages`,
			].join("\n");
		},
	});
}
