import { generators } from "../generators.js";

/**
 * DB generator that watches src/db schema files and generates types + migrations.
 *
 * Uses a schema file to detect changes and generate migrations.
 */
export function dbGenerator() {
	return generators({
		watch: "src/db/**/*.schema.ts",
		output: ".space/db.ts",
		generate(files) {
			// Dynamic import of schema files would happen here
			// For now, generate a stub that imports from the user's schema
			return [
				`// @ts-nocheck`,
				`// Auto-generated by spaceGenerators — DO NOT EDIT`,
				`// Schema files:`,
				...files.map((f) => `//   ${f}`),
				``,
				`// Import your schema definitions and use generateTypes()`,
				`// to produce Kysely-compatible types.`,
			].join("\n");
		},
	});
}
