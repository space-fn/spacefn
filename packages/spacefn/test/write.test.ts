import { mkdir, mkdtemp, readFile, rm, stat, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";

import { afterEach, beforeEach, describe, expect, it } from "@effect/vitest";
import { Effect } from "effect";

import { writeGenerated } from "../src/codegen/write.ts";

const HEADER = "// Generated by space gen. Do not edit.\n";

let root: string;
beforeEach(async () => {
	root = await mkdtemp(join(tmpdir(), "spacefn-write-"));
});
afterEach(() => rm(root, { recursive: true, force: true }));

const space = (file: string) => join(root, ".space", file);

describe("writeGenerated", () => {
	it.effect("writes new files and reports only real changes", () =>
		Effect.gen(function* () {
			const files = { "manifest.ts": `${HEADER}a`, "db/main.ts": `${HEADER}b` };
			expect(yield* writeGenerated(root, files)).toEqual({
				written: ["db/main.ts", "manifest.ts"],
				removed: [],
			});
			const before = (yield* Effect.promise(() => stat(space("manifest.ts")))).mtimeMs;

			const again = yield* writeGenerated(root, { ...files, "db/main.ts": `${HEADER}c` });
			expect(again).toEqual({ written: ["db/main.ts"], removed: [] });
			expect((yield* Effect.promise(() => stat(space("manifest.ts")))).mtimeMs).toBe(before);
		}),
	);

	it.effect("deletes stale generated files and leaves everything else alone", () =>
		Effect.gen(function* () {
			yield* Effect.promise(async () => {
				await mkdir(space("db"), { recursive: true });
				await mkdir(space(".alchemy/state"), { recursive: true });
				await mkdir(space("dist"), { recursive: true });
				await writeFile(space("db/old.ts"), `${HEADER}x`);
				await writeFile(space("notes.ts"), "// mine\n");
				await writeFile(space(".alchemy/state/s.ts"), `${HEADER}state`);
				await writeFile(space("dist/index.ts"), `${HEADER}built`);
			});
			const result = yield* writeGenerated(root, { "manifest.ts": `${HEADER}a` });
			expect(result.removed).toEqual(["db/old.ts"]);
			const read = (file: string) => readFile(space(file), "utf8");
			expect(yield* Effect.promise(() => read("notes.ts"))).toBe("// mine\n");
			expect(yield* Effect.promise(() => read(".alchemy/state/s.ts"))).toContain("state");
			expect(yield* Effect.promise(() => read("dist/index.ts"))).toContain("built");
		}),
	);
});
