import { describe, expect, it } from "@effect/vitest";

import { renderDb } from "../src/codegen/render-db.ts";
import { analyzeQuery } from "../src/sql/index.ts";
import { scratchDatabase } from "../src/sql/node/index.ts";

const migrations = [
	{
		id: "0001_todos",
		sql: "CREATE TABLE todos (id INTEGER PRIMARY KEY, title TEXT NOT NULL, note TEXT, done INTEGER NOT NULL DEFAULT 0);",
		down: "DROP TABLE todos;",
	},
];

const queries = async (files: Record<string, string>) => {
	const scratch = await scratchDatabase(migrations);
	return Promise.all(
		Object.entries(files).map(([file, text]) => analyzeQuery(scratch, file, text)),
	);
};

describe("renderDb", () => {
	it("quotes the key of a query in a folder and prefixes its types", async () => {
		const [query] = await queries({
			"mark-done.sql": "-- @param id number\nUPDATE todos SET done = 1 WHERE id = :id",
		});
		const source = renderDb({
			name: "main",
			driver: "d1",
			migrateOn: "startup",
			open: "startup",
			binding: "DB_MAIN",
			migrations,
			// As scanQueries names queries/todos/mark-done.sql.
			queries: [{ ...query!, name: "todos.markDone" }],
		});
		expect(source).toContain("export interface TodosMarkDoneParams {");
		expect(source).toContain('\t"todos.markDone": {\n\t\tmode: "exec",');
		expect(source).toContain(
			'\t"todos.markDone": { params: TodosMarkDoneParams; row: never; mode: "exec" };',
		);
	});

	it("renders migrations, query parts and Params/Row types", async () => {
		const source = renderDb({
			name: "main",
			driver: "d1",
			migrateOn: "startup",
			open: "startup",
			binding: "DB_MAIN",
			migrations,
			queries: await queries({
				"list-todos.sql": [
					"-- @param done number",
					"-- @param title string?",
					"SELECT id, title, note FROM todos WHERE done = :done",
					"-- case",
					"-- when title",
					"AND title = :title",
					"-- end",
				].join("\n"),
				"add-todo.sql": "-- @param title string\nINSERT INTO todos (title) VALUES (:title)",
			}),
		});
		expect(source).toMatchInlineSnapshot(`
			"// Generated by space gen. Do not edit.
			import { database } from "spacefn/internal/runtime";

			export interface ListTodosParams {
				readonly done: number;
				readonly title?: string | null;
			}

			export interface ListTodosRow {
				readonly id: number;
				readonly title: string;
				readonly note: string | null;
			}

			export interface AddTodoParams {
				readonly title: string;
			}

			export const name = "main";
			export const driver = "d1";
			export const migrateOn = "startup";

			export const migrations = [
				{ id: "0001_todos", sql: "CREATE TABLE todos (id INTEGER PRIMARY KEY, title TEXT NOT NULL, note TEXT, done INTEGER NOT NULL DEFAULT 0);", down: "DROP TABLE todos;" },
			] as const;

			export const queries = {
				listTodos: {
					mode: "many",
					columns: { "id": "number", "title": "string", "note": "string?" },
					parts: [
						{ sql: "SELECT id, title, note FROM todos WHERE done = ?", params: ["done"], gate: null },
						{ sql: "AND title = ?", params: ["title"], gate: ["title"] },
					],
				},
				addTodo: {
					mode: "exec",
					columns: {},
					parts: [
						{ sql: "INSERT INTO todos (title) VALUES (?)", params: ["title"], gate: null },
					],
				},
			} as const;

			export interface Queries {
				listTodos: { params: ListTodosParams; row: ListTodosRow; mode: "many" };
				addTodo: { params: AddTodoParams; row: never; mode: "exec" };
			}

			export class MainDb extends database<MainDb, Queries>()({ name, migrations, queries, migrateOn }) {}

			export default MainDb;
			"
		`);
	});
});
