import { describe, expect, it } from "@effect/vitest";
import { Effect } from "effect";

import type { Target } from "../src/app-config.ts";
import { planApp } from "../src/codegen/plan.ts";
import { renderApp } from "../src/codegen/render.ts";
import type { AppTree } from "../src/codegen/scan-app.ts";

const empty: AppTree = {
	env: false,
	entry: true,
	routes: [],
	queues: [],
	crons: [],
	cronSources: {},
	durableObjects: [],
	workflows: [],
	assets: [],
	islands: [],
	public: [],
	db: [],
	gitignore: ".space/\n",
};

const render = (target: Target, tree: Partial<AppTree> = {}) =>
	renderApp(
		Effect.runSync(
			planApp(
				{ ...empty, ...tree },
				{ target, name: "todo", folders: ["lib"], packages: [] },
				"dev",
			),
		),
	);

describe("renderApp", () => {
	it("gives Cloudflare one Worker entry that also exports Durable Objects and workflows", () => {
		const files = render("cloudflare", {
			durableObjects: ["chat-room.ts"],
			workflows: ["order-flow.ts"],
			db: [
				{
					name: "main",
					migrations: [],
					queries: [],
					config: '{ "driver": "d1", "migrateOn": "startup" }',
				},
			],
		});
		expect(Object.keys(files).sort()).toEqual([
			"assets.d.ts",
			"db/main.ts",
			"entry.ts",
			"infra.ts",
			"islands.ts",
			"manifest.ts",
			"vite.config.ts",
		]);
		expect(files["entry.ts"]).toMatchInlineSnapshot(`
			"// Generated by space gen. Do not edit.
			import { worker } from "spacefn/cloudflare";
			import entry from "../app/entry.ts";

			export default worker(entry);
			// The Durable Objects behind Bus and RateLimiter.
			export { SpaceBus, SpaceRateLimiter } from "spacefn/cloudflare";
			export { default as ChatRoom } from "../app/durable-objects/chat-room.ts";
			export { default as OrderFlow } from "../app/workflows/order-flow.ts";
			"
		`);
	});

	it("gives Bun a fetch-handler app and a production server", () => {
		const files = render("bun");
		expect(Object.keys(files).sort()).toEqual([
			"app.ts",
			"assets.d.ts",
			"infra.ts",
			"islands.ts",
			"manifest.ts",
			"server.ts",
			"vite.config.ts",
		]);
		expect(files["app.ts"]).toMatchInlineSnapshot(`
			"// Generated by space gen. Do not edit.
			import { bunApp } from "spacefn/bun";
			import entry from "../app/entry.ts";

			export default bunApp(entry);
			"
		`);
		expect(files["server.ts"]).toMatchInlineSnapshot(`
			"// Generated by space gen. Do not edit.
			import { dirname, join } from "node:path";
			import { fileURLToPath } from "node:url";

			import { serve } from "spacefn/bun";
			import entry from "../app/entry.ts";

			// Built to dist/server/index.js, beside dist/client.
			await serve(entry, { client: join(dirname(fileURLToPath(import.meta.url)), "..", "client") });
			"
		`);
	});

	it("re-exports configs/vite.ts as .space/vite.config.ts, for Alchemy", () => {
		expect(render("bun", { assets: ["main.ts"] })["vite.config.ts"]).toMatchInlineSnapshot(`
			"// Generated by space gen. Do not edit.
			// Alchemy looks for vite.config.ts where it runs Vite. The config is the app's: configs/vite.ts.
			export { default } from "../configs/vite.ts";
			"
		`);
	});

	it("names the asset entries for assets(...)", () => {
		expect(render("bun", { assets: ["main.ts", "site.css"] })["assets.d.ts"])
			.toMatchInlineSnapshot(`
			"// Generated by space gen. Do not edit.
			export {};

			declare module "spacefn/assets" {
				interface ClientEntries {
					"main": "app/assets/main.ts";
					"site": "app/assets/site.css";
				}
			}
			"
		`);
	});

	it("types island(name, props) by each component, and starts each with its framework", () => {
		const files = renderApp(
			Effect.runSync(
				planApp(
					{ ...empty, islands: ["modules/cart/ui/Cart.island.tsx", "lib/ui/Menu.island.vue"] },
					{ target: "bun", name: "todo", folders: ["lib", "modules"], packages: ["react-dom"] },
					"dev",
				),
			),
		);
		expect(files["islands.ts"]).toContain(
			'\t"Cart": FunctionProps<typeof import("../modules/cart/ui/Cart.island.tsx").default>;',
		);
		expect(files["islands.ts"]).toContain(
			'import { islands, type FunctionProps, type VueProps } from "spacefn/islands";',
		);
		expect(files["islands/Cart.ts"]).toContain('import { createRoot } from "react-dom/client";');
		expect(files["islands/Cart.ts"]).toContain(
			'import Component from "../../modules/cart/ui/Cart.island.tsx";',
		);
		expect(files["islands/Cart.ts"]).toContain('defineIsland("Cart", (element, props) => {');
		expect(files["islands/Menu.ts"]).toContain("const app = createApp(Component, props);");
	});

	it("gives configs/infra.ts what the file conventions ask for, as plain data", () => {
		const cloudflare = render("cloudflare", {
			env: true,
			queues: ["emails.ts"],
			crons: ["a.ts", "b.ts"],
			cronSources: {
				"a.ts": 'export default cron("0 3 * * *", a);',
				"b.ts": 'export default cron("0 3 * * *", b);',
			},
			durableObjects: ["chat-room.ts"],
			db: [
				{
					name: "main",
					migrations: [],
					queries: [],
					config: '{ "driver": "d1", "migrateOn": "startup" }',
				},
				// The app's to create and open: nothing for the infra, and a flag in the manifest.
				{
					name: "tenant",
					migrations: [],
					queries: [],
					config: '{ "driver": "libsql", "migrateOn": "startup", "open": "manual" }',
				},
			],
		});
		expect(cloudflare["manifest.ts"]).toContain(
			'{ name: "tenant", driver: "libsql", binding: "DB_TENANT", open: "manual", module: db1 }',
		);
		expect(cloudflare["infra.ts"]).toMatchInlineSnapshot(`
			"// Generated by space gen. Do not edit.
			import type { InfraApp } from "spacefn/infra";

			/** The app as configs/infra.ts loops over it: from package.json and app/. */
			export const app: InfraApp = {
				name: "todo",
				folders: [
					"lib",
				],
				databases: [
					{"name":"main","binding":"DB_MAIN","driver":"d1"},
				],
				queues: [
					{"name":"emails","binding":"QUEUE_EMAILS"},
				],
				crons: [
					"0 3 * * *",
				],
				durableObjects: [
					{"className":"ChatRoom","binding":"DO_CHAT_ROOM"},
				],
				workflows: [],
			};
			"
		`);
	});
});
