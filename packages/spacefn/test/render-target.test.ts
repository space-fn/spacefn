import { describe, expect, it } from "@effect/vitest";
import { Effect } from "effect";

import { planApp } from "../src/codegen/plan.ts";
import { renderApp } from "../src/codegen/render.ts";
import type { AppTree } from "../src/codegen/scan-app.ts";
import type { Target } from "../src/space-config.ts";

const empty: AppTree = {
	env: false,
	layers: false,
	viteConfig: false,
	routes: [],
	pages: [],
	middleware: [],
	queues: [],
	crons: [],
	cronSources: {},
	uses: { kv: false, blob: false },
	durableObjects: [],
	workflows: [],
	client: [],
	db: [],
	gitignore: ".space/\n",
};

const render = (target: Target, tree: Partial<AppTree> = {}) =>
	renderApp(
		Effect.runSync(
			planApp(
				{ ...empty, ...tree },
				{ target, name: "todo", aliases: { "@lib": "lib" }, db: {} },
				"dev",
			),
		),
	);

describe("renderApp", () => {
	it("gives Cloudflare one Worker entry that also exports Durable Objects and workflows", () => {
		const files = render("cloudflare", {
			durableObjects: ["chat-room.ts"],
			workflows: ["order-flow.ts"],
			db: [{ name: "main", migrations: [], queries: [] }],
		});
		expect(Object.keys(files).sort()).toEqual([
			"assets.d.ts",
			"db/main.ts",
			"entry.ts",
			"manifest.ts",
			"tsconfig.json",
			"vite.config.ts",
		]);
		expect(files["entry.ts"]).toMatchInlineSnapshot(`
			"// Generated by space gen. Do not edit.
			import { worker } from "@spacefn/cloudflare";
			import { manifest } from "./manifest.ts";

			export default worker(manifest);
			// The Durable Objects behind Bus and RateLimiter.
			export { SpaceBus, SpaceRateLimiter } from "@spacefn/cloudflare";
			export { default as ChatRoom } from "../app/durable-objects/chat-room.ts";
			export { default as OrderFlow } from "../app/workflows/order-flow.ts";
			"
		`);
	});

	it("gives Bun a fetch-handler app and a production server", () => {
		const files = render("bun");
		expect(Object.keys(files).sort()).toEqual([
			"app.ts",
			"assets.d.ts",
			"manifest.ts",
			"server.ts",
			"tsconfig.json",
			"vite.config.ts",
		]);
		expect(files["app.ts"]).toMatchInlineSnapshot(`
			"// Generated by space gen. Do not edit.
			import { app } from "@spacefn/bun";
			import { manifest } from "./manifest.ts";

			export default app(manifest);
			"
		`);
		expect(files["server.ts"]).toMatchInlineSnapshot(`
			"// Generated by space gen. Do not edit.
			import { dirname, join } from "node:path";
			import { fileURLToPath } from "node:url";

			import { serve } from "@spacefn/bun";
			import app from "./app.ts";

			// Built to .space/dist/server/index.js, beside .space/dist/client.
			await serve(app, { client: join(dirname(fileURLToPath(import.meta.url)), "..", "client") });
			"
		`);
	});

	it("uses the spacefn plugin alone when there is no configs/vite.config.ts", () => {
		expect(render("bun", { client: ["main.ts"] })["vite.config.ts"]).toMatchInlineSnapshot(`
			"// Generated by space gen. Do not edit.
			import { fileURLToPath } from "node:url";

			import { space } from "@spacefn/infra/vite";
			import { defineConfig } from "vite";

			export default defineConfig({ plugins: [space({ target: "bun", root: fileURLToPath(new URL("..", import.meta.url)), client: ["app/client/main.ts"], aliases: {"@lib":"lib"} })] });
			"
		`);
	});

	it("merges configs/vite.config.ts, in object or function form", () => {
		expect(render("cloudflare", { viteConfig: true })["vite.config.ts"]).toMatchInlineSnapshot(`
			"// Generated by space gen. Do not edit.
			import { fileURLToPath } from "node:url";

			import { space } from "@spacefn/infra/vite";
			import { defineConfig, mergeConfig } from "vite";
			import user from "../configs/vite.config.ts";

			export default defineConfig(async (env) =>
				mergeConfig(typeof user === "function" ? await user(env) : await user, { plugins: [space({ target: "cloudflare", root: fileURLToPath(new URL("..", import.meta.url)), client: [], aliases: {"@lib":"lib"} })] }),
			);
			"
		`);
	});

	it("declares the aliases as tsconfig paths", () => {
		expect(JSON.parse(render("bun")["tsconfig.json"] ?? "")).toEqual({
			compilerOptions: { paths: { "@space/*": ["./*"], "@lib/*": ["../lib/*"] } },
		});
	});
});
