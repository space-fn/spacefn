import { expect, test } from "vite-plus/test";

import { generateRoutesSource } from "../src/routes/generate";

test("generates imports and mounts in order", () => {
	const source = generateRoutesSource([
		{ file: "index.ts", path: "/" },
		{ file: "users/[id].ts", path: "/users/:id" },
	]);
	expect(source).toBe(`// Generated by space. Do not edit.
import { mountRoute, type Hono } from "spacefn/runtime";
import * as route0 from "../app/routes/index";
import * as route1 from "../app/routes/users/[id]";

export function registerRoutes(app: Hono): void {
\tmountRoute(app, "/", route0);
\tmountRoute(app, "/users/:id", route1);
}
`);
});

test("generates an empty registrar without routes", () => {
	expect(generateRoutesSource([])).toContain(
		"export function registerRoutes(app: Hono): void {\n}",
	);
});

test("registers literal pages before dynamic routes", () => {
	const source = generateRoutesSource(
		[{ file: "[id].ts", path: "/:id" }],
		[{ file: "hello.page.ts", path: "/hello" }],
	);
	expect(source.indexOf('mountPage(app, "/hello"')).toBeLessThan(
		source.indexOf('mountRoute(app, "/:id"'),
	);
	expect(source).toContain('import { mountPage, mountRoute, type Hono } from "spacefn/runtime";');
});
