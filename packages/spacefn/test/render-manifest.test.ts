import { describe, expect, it } from "@effect/vitest";
import { Effect } from "effect";

import { planApp } from "../src/codegen/plan.ts";
import { renderManifest } from "../src/codegen/render-manifest.ts";
import type { AppTree } from "../src/codegen/scan-app.ts";

const empty: AppTree = {
	env: false,
	layers: false,
	viteConfig: false,
	routes: [],
	pages: [],
	middleware: [],
	queues: [],
	crons: [],
	durableObjects: [],
	workflows: [],
	client: [],
	db: [],
	gitignore: ".space/\n",
};

const render = (tree: Partial<AppTree>) =>
	renderManifest(
		Effect.runSync(
			planApp(
				{ ...empty, ...tree },
				{ target: "cloudflare", name: "todo", aliases: {}, db: {} },
				"dev",
			),
		),
	);

describe("renderManifest", () => {
	it("renders an empty app", () => {
		expect(render({})).toMatchInlineSnapshot(`
			"// Generated by space gen. Do not edit.
			import type { SpaceManifest } from "spacefn";

			export const manifest = {
				name: "todo",
				routes: [],
				middleware: [],
				queues: [],
				crons: [],
				db: [],
			} as const satisfies SpaceManifest;
			"
		`);
	});

	it("imports every convention file and lists it in order", () => {
		expect(
			render({
				env: true,
				layers: true,
				routes: ["index.ts", "files/[...path].ts"],
				pages: ["users/[id].ts"],
				middleware: ["1-auth.ts"],
				queues: ["emails.ts"],
				crons: ["nightly.ts"],
				db: [{ name: "main", migrations: [], queries: [] }],
			}),
		).toMatchInlineSnapshot(`
			"// Generated by space gen. Do not edit.
			import type { SpaceManifest } from "spacefn";
			import * as route0 from "../app/routes/index.ts";
			import * as route1 from "../app/routes/files/[...path].ts";
			import * as route2 from "../app/pages/users/[id].ts";
			import * as middleware0 from "../app/middleware/1-auth.ts";
			import * as queue0 from "../app/queues/emails.ts";
			import * as cron0 from "../app/crons/nightly.ts";
			import * as db0 from "./db/main.ts";
			import * as env from "../app/env.ts";
			import * as layers from "../app/layers.ts";

			export const manifest = {
				name: "todo",
				env: { file: "app/env.ts", module: env },
				layers: { file: "app/layers.ts", module: layers },
				routes: [
					{ kind: "route", path: "/", params: [], file: "app/routes/index.ts", module: route0 },
					{ kind: "route", path: "/files/*", params: ["path"], catchAll: "path", file: "app/routes/files/[...path].ts", module: route1 },
					{ kind: "page", path: "/users/:id", params: ["id"], file: "app/pages/users/[id].ts", module: route2 },
				],
				middleware: [
					{ file: "app/middleware/1-auth.ts", module: middleware0 },
				],
				queues: [
					{ name: "emails", binding: "QUEUE_EMAILS", file: "app/queues/emails.ts", module: queue0 },
				],
				crons: [
					{ name: "nightly", file: "app/crons/nightly.ts", module: cron0 },
				],
				db: [
					{ name: "main", driver: "d1", binding: "DB_MAIN", module: db0 },
				],
			} as const satisfies SpaceManifest;
			"
		`);
	});
});
