import type { PageFile } from "../pages/scan";
import type { RouteFile } from "./scan";
import { compareRoutePaths } from "./scan";

const EXTENSION = /\.(?:[cm]?[jt]s|[jt]sx)$/;

type Registration = (RouteFile & { kind: "route" }) | (PageFile & { kind: "page" });

/** Source of `.space/routes.ts`, which registers routes and pages by path specificity. */
export function generateRoutesSource(routes: RouteFile[], pages: PageFile[] = []): string {
	const registrations: Registration[] = [
		...routes.map((route) => ({ ...route, kind: "route" as const })),
		...pages.map((page) => ({ ...page, kind: "page" as const })),
	].sort(compareRoutePaths);
	const imports = registrations.flatMap((registration, i) => {
		if (registration.kind === "route") {
			return [
				`import * as route${i} from "../app/routes/${registration.file.replace(EXTENSION, "")}";`,
			];
		}
		return [
			`import page${i} from "../app/pages/${registration.file.replace(EXTENSION, "")}";`,
			...(registration.server
				? [
						`import * as server${i} from "../app/pages/${registration.server.replace(EXTENSION, "")}";`,
					]
				: []),
		];
	});
	const mounts = registrations.map((registration, i) =>
		registration.kind === "route"
			? `\tmountRoute(app, ${JSON.stringify(registration.path)}, route${i});`
			: `\tmountPage(app, ${JSON.stringify(registration.path)}, page${i}, ${registration.server ? `server${i}` : "undefined"});`,
	);
	const helpers = [
		...(pages.length > 0 ? ["mountPage"] : []),
		...(routes.length > 0 ? ["mountRoute"] : []),
		"type Hono",
	];

	return [
		"// Generated by space. Do not edit.",
		`import { ${helpers.join(", ")} } from "spacefn/runtime";`,
		...imports,
		"",
		"export function registerRoutes(app: Hono): void {",
		...mounts,
		"}",
		"",
	].join("\n");
}
