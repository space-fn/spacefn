import type { PageFile } from "./scan";

function stripExtension(file: string): string {
	return file.replace(/\.(?:[cm]?[jt]s|[jt]sx)$/, "");
}

/** Source of `.space/pages.ts`: registers every page and its server module. */
export function generatePagesSource(pages: PageFile[]): string {
	const imports = pages.flatMap((page, i) => [
		`import page${i} from "../app/pages/${stripExtension(page.file)}";`,
		...(page.server
			? [`import * as server${i} from "../app/pages/${stripExtension(page.server)}";`]
			: []),
	]);
	const mounts = pages.map(
		(page, i) =>
			`\tmountPage(app, ${JSON.stringify(page.path)}, page${i}, ${page.server ? `server${i}` : "undefined"});`,
	);
	return [
		"// Generated by space. Do not edit.",
		'import { mountPage, type Hono } from "spacefn/runtime";',
		...imports,
		"",
		"export function registerPages(app: Hono): void {",
		...mounts,
		"}",
		"",
	].join("\n");
}
