function className(file: string): string {
	const base = file.replace(/\.(?:[cm]?[jt]s|[jt]sx)$/, "");
	return base
		.split(/[-_]/)
		.filter(Boolean)
		.map((part) => part.charAt(0).toUpperCase() + part.slice(1))
		.join("");
}

function snakeCase(name: string): string {
	return name
		.replace(/([A-Z])/g, "_$1")
		.replace(/^_/, "")
		.toUpperCase();
}

export function bindingType(descriptor: { type?: string }, durableObjectClass?: string): string {
	const type = descriptor?.type ?? "text";
	switch (type) {
		case "d1":
			return "D1Database";
		case "r2":
			return "R2Bucket";
		case "kv":
			return "KVNamespace";
		case "durable-object":
			return durableObjectClass
				? `DurableObjectNamespace<${durableObjectClass}>`
				: "DurableObjectNamespace";
		case "workflow":
			return "Workflow";
		case "send-email":
			return "SendEmail";
		case "queue":
			return "Queue<unknown>";
		case "text":
		case "secret":
		default:
			return "string";
	}
}

export interface BindingsInput {
	envFields: Array<{ name: string }>;
	cloudflareBindings: Record<string, { type?: string }>;
	durableObjectFiles: string[];
	workflowFiles: string[];
	queueFiles: string[];
}

export function generateBindingsSource(input: BindingsInput): string {
	const { envFields, cloudflareBindings, durableObjectFiles, workflowFiles, queueFiles } = input;

	// Map binding name → DO class name
	const doClassByBinding: Record<string, string> = {};
	for (const file of durableObjectFiles) {
		const cls = className(file);
		// Binding name convention: DO_<SNAKE_CASE>
		doClassByBinding[`DO_${snakeCase(cls)}`] = cls;
	}

	const lines: string[] = [
		"// Generated by space. Do not edit.",
		'import type { D1Database, R2Bucket, KVNamespace, Queue, DurableObjectNamespace, Workflow, SendEmail } from "@cloudflare/workers-types";',
	];

	// Import DO classes
	for (const file of durableObjectFiles) {
		const cls = className(file);
		const base = file.replace(/\.(?:[cm]?[jt]sx?)$/, "");
		lines.push(`import type { ${cls} } from "../app/durable-objects/${base}";`);
	}

	lines.push("");
	const body: string[] = [];
	for (const f of envFields) {
		body.push(`\t${f.name}: string;`);
	}
	for (const [name, desc] of Object.entries(cloudflareBindings)) {
		const cls = doClassByBinding[name];
		const t = bindingType(desc, cls);
		body.push(`\t${name}: ${t};`);
	}
	// Durable Objects (convention: binding name = DO_<SNAKE_CASE>)
	for (const file of durableObjectFiles) {
		const cls = className(file);
		const binding = `DO_${snakeCase(cls)}`;
		if (!cloudflareBindings[binding]) body.push(`\t${binding}: DurableObjectNamespace<${cls}>;`);
	}
	// Workflows (convention: binding name = WF_<SNAKE_CASE>)
	for (const file of workflowFiles) {
		const cls = className(file);
		const binding = `WF_${snakeCase(cls)}`;
		if (!cloudflareBindings[binding]) body.push(`\t${binding}: Workflow;`);
	}
	// Queues (convention: binding name = QUEUE_<NAME>)
	for (const file of queueFiles) {
		const base = file.replace(/\.(?:[cm]?[jt]s|[jt]sx)$/, "");
		const binding = `QUEUE_${base.replace(/[^A-Za-z0-9]/g, "_").toUpperCase()}`;
		if (!cloudflareBindings[binding]) body.push(`\t${binding}: Queue<unknown>;`);
	}

	lines.push('declare module "spacefn/env" {');
	lines.push("\tinterface CloudflareBindings {");
	for (const b of body) lines.push(`\t${b.trim()}`);
	lines.push("\t}");
	lines.push("\tinterface Register {");
	lines.push("\t\tbindings: CloudflareBindings;");
	lines.push("\t}");
	lines.push("}");
	lines.push("");

	return lines.join("\n");
}
