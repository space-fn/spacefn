import type { AppPlan } from "./plan.ts";

export const GENERATED = "// Generated by space gen. Do not edit.";

/** Import specifier from a file directly in `.space/` to a file given from the app root. */
export const fromSpace = (appFile: string): string => `../${appFile}`;

const str = JSON.stringify;

/** Source of `.space/manifest.ts`: every convention file, imported and listed. */
export const renderManifest = (plan: AppPlan): string => {
	const imports: string[] = [];
	const use = (alias: string, file: string) => {
		imports.push(`import * as ${alias} from ${str(file)};`);
		return alias;
	};
	const ref = (alias: string, file: string) =>
		`{ file: ${str(file)}, module: ${use(alias, fromSpace(file))} }`;

	const routes = plan.routes.map((route, i) => {
		const fields = [
			`path: ${str(route.path)}`,
			`params: ${str(route.params)}`,
			...(route.catchAll ? [`catchAll: ${str(route.catchAll)}`] : []),
			`file: ${str(route.file)}`,
			`module: ${use(`route${i}`, fromSpace(route.file))}`,
		];
		return `\t\t{ ${fields.join(", ")} },`;
	});
	const middleware = plan.middleware.map(
		({ folder, file }, i) =>
			`\t\t{ folder: ${str(folder)}, file: ${str(file)}, module: ${use(`middleware${i}`, fromSpace(file))} },`,
	);
	const queues = plan.queues.map(
		(q, i) =>
			`\t\t{ name: ${str(q.name)}, binding: ${str(q.binding)}, file: ${str(q.file)}, module: ${use(`queue${i}`, fromSpace(q.file))} },`,
	);
	const crons = plan.crons.map(
		(c, i) =>
			`\t\t{ name: ${str(c.name)}, file: ${str(c.file)}, module: ${use(`cron${i}`, fromSpace(c.file))} },`,
	);
	const db = plan.db.map(
		(d, i) =>
			`\t\t{ name: ${str(d.name)}, driver: ${str(d.driver)}, binding: ${str(d.binding)}, module: ${use(`db${i}`, `./db/${d.name}.ts`)} },`,
	);
	const env = plan.env ? [`\tenv: ${ref("env", "configs/env.ts")},`] : [];
	const list = (key: string, lines: string[]) =>
		lines.length === 0 ? [`\t${key}: [],`] : [`\t${key}: [`, ...lines, "\t],"];

	const body = [
		"export const manifest = {",
		`\tname: ${str(plan.name)},`,
		...env,
		...list("routes", routes),
		...list("middleware", middleware),
		...list("queues", queues),
		...list("crons", crons),
		...list("db", db),
		"} as const satisfies SpaceManifest;",
	];

	return [
		GENERATED,
		'import type { SpaceManifest } from "spacefn";',
		...imports,
		"",
		...body,
		"",
	].join("\n");
};
