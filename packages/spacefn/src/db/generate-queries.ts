import type { InferredQuery } from "./infer";
import type { QueryMode } from "./query-file";

export interface GeneratedQuery extends InferredQuery {
	/** Parameter names in placeholder order, for binding. */
	paramNames: string[];
	/** Declared types for parameters, from `@param` lines. Others are `SqlValue`. */
	paramTypes: Record<string, string>;
	/** The SQL with `?` placeholders, as sent to the database. */
	boundSql: string;
}

/** The return type of a query function, by mode. */
export const RESULT = (mode: QueryMode, row: string) =>
	mode === "many" ? `${row}[]` : mode === "one" ? `${row} | undefined` : "void";

/** The TypeScript type of a query's parameter object. */
export function paramsType(query: GeneratedQuery): string {
	if (query.paramNames.length === 0) return "Record<string, never>";
	const fields = [...new Set(query.paramNames)].map(
		(name) => `${name}: ${query.paramTypes[name] ?? "SqlValue"}`,
	);
	return `{ ${fields.join("; ")} }`;
}

/** The TypeScript type of one result column. */
export function columnType(column: { type: string; nullable: boolean }): string {
	const base =
		column.type === "bytes" ? "Uint8Array" : column.type === "unknown" ? "SqlValue" : column.type;
	return column.nullable ? `${base} | null` : base;
}

/** `findTodo` becomes `FindTodo`. */
export function pascal(name: string): string {
	return name.charAt(0).toUpperCase() + name.slice(1);
}

/** Source of `.space/queries.ts`: one typed function per query file. */
export function generateQueriesSource(queries: GeneratedQuery[]): string {
	const blocks = queries.map((query) => {
		const row = `${pascal(query.name)}Row`;
		const fields = query.columns.map((column) => `\t${column.name}: ${columnType(column)};`);
		const paramType = paramsType(query);
		const values = query.paramNames.map((name) => `params.${name}`).join(", ");
		const hasRows = query.mode !== "exec";
		const rows = query.columns.length ? [`export interface ${row} {`, ...fields, "}", ""] : [];
		const resultType = hasRows ? RESULT(query.mode, row) : "void";
		const body =
			query.mode === "exec"
				? `\tawait queryD1(db, ${JSON.stringify(query.boundSql)}, [${values}]);`
				: query.mode === "one"
					? `\treturn (await queryD1<${row}>(db, ${JSON.stringify(query.boundSql)}, [${values}]))[0];`
					: `\treturn queryD1<${row}>(db, ${JSON.stringify(query.boundSql)}, [${values}]);`;
		return [
			...(hasRows ? rows : []),
			`/** ${query.sql.replace(/\*\//g, "* /")} */`,
			`export async function ${query.name}(db: D1Reader, params: ${paramType}): Promise<${resultType}> {`,
			body,
			"}",
			"",
		].join("\n");
	});

	return [
		"// Generated by space. Do not edit.",
		'import { queryD1, type D1Reader, type SqlValue } from "spacefn/db";',
		"",
		...blocks,
	].join("\n");
}
