import { columnType, paramsType, pascal } from "./generate-queries";
import type { GeneratedQuery } from "./generate-queries";
import type { Migration } from "./migrate";

/** Source of `.space/db/<name>.ts`: migrations and typed queries for one database. */
export function generateDbSource(
	name: string,
	migrations: Migration[],
	queries: GeneratedQuery[],
): string {
	const blocks: string[] = [];

	blocks.push("// Generated by space. Do not edit.");
	blocks.push(
		'import { d1Executor, type DbReader, type Migration, type SqlValue } from "spacefn/db";',
	);
	blocks.push("");

	blocks.push("export const migrations: Migration[] = [");
	for (const migration of migrations) {
		const down = migration.down ? `, down: ${JSON.stringify(migration.down)}` : "";
		blocks.push(
			`\t{ id: ${JSON.stringify(migration.id)}, sql: ${JSON.stringify(migration.sql)}${down} },`,
		);
	}
	blocks.push("];");
	blocks.push("");

	blocks.push(
		'import { applyMigrations, rollbackMigrations, type MigrationExecutor } from "spacefn/db";',
	);
	blocks.push("");
	blocks.push(
		'export async function migrate(db: MigrationExecutor, action: "up" | "down" = "up", steps = 1): Promise<string[]> {',
	);
	blocks.push('\tif (action === "up") return applyMigrations(db, migrations);');
	blocks.push("\treturn rollbackMigrations(db, migrations, { steps });");
	blocks.push("}");
	blocks.push("");
	blocks.push("const ready = new WeakMap<WeakKey, Promise<string[]>>();");
	blocks.push("");
	blocks.push("export function migrated(db: unknown): Promise<string[]> {");
	blocks.push("\tlet pending = ready.get(db as WeakKey);");
	blocks.push("\tif (!pending) {");
	blocks.push("\t\tpending = applyMigrations(d1Executor(db as never), migrations);");
	blocks.push("\t\tpending.catch(() => {");
	blocks.push("\t\t\tready.delete(db as WeakKey);");
	blocks.push("\t\t});");
	blocks.push("\t\tready.set(db as WeakKey, pending);");
	blocks.push("\t}");
	blocks.push("\treturn pending;");
	blocks.push("}");

	for (const query of queries) {
		const row = `${pascal(query.name)}Row`;
		const hasRows = query.mode !== "exec";
		if (hasRows && query.columns.length > 0) {
			blocks.push(`export interface ${row} {`);
			for (const column of query.columns) {
				blocks.push(`\t${column.name}: ${columnType(column)};`);
			}
			blocks.push("}");
			blocks.push("");
		}
		const paramType = paramsType(query);
		const values = query.paramNames.map((name) => `params.${name}`).join(", ");
		const resultType = hasRows
			? query.mode === "many"
				? `${row}[]`
				: `${row} | undefined`
			: "void";
		const isDynamic = (query.parts ?? []).some((p) => p.gate !== null);
		let body: string;
		if (!isDynamic) {
			body =
				query.mode === "exec"
					? `\tawait db.query(${JSON.stringify(query.boundSql)}, [${values}]);`
					: query.mode === "one"
						? `\treturn (await db.query<${row}>(${JSON.stringify(query.boundSql)}, [${values}]))[0];`
						: `\treturn db.query<${row}>(${JSON.stringify(query.boundSql)}, [${values}]);`;
		} else {
			const lines: string[] = [];
			lines.push("\tconst __sql: string[] = [];");
			lines.push("\tconst __values: unknown[] = [];");
			for (const part of query.parts) {
				if (part.gate === null) {
					lines.push(`\t__sql.push(${JSON.stringify(part.sql)});`);
					for (const n of part.paramNames) lines.push(`\t__values.push(params.${n});`);
				} else {
					const cond = part.gate.map((g) => `params.${g} !== undefined`).join(" && ");
					lines.push(`\tif (${cond}) {`);
					lines.push(`\t\t__sql.push(${JSON.stringify(part.sql)});`);
					for (const n of part.paramNames) lines.push(`\t\t__values.push(params.${n}!);`);
					lines.push("\t}");
				}
			}
			const call =
				query.mode === "exec"
					? '\tawait db.query(__sql.join(""), __values);'
					: query.mode === "one"
						? `\treturn (await db.query<${row}>(__sql.join(""), __values))[0];`
						: `\treturn db.query<${row}>(__sql.join(""), __values);`;
			lines.push(call);
			body = lines.join("\n");
		}
		blocks.push(`/** ${query.sql.replace(/\*\//g, "* /")} */`);
		blocks.push(
			`export async function ${query.name}(db: DbReader, params: ${paramType}): Promise<${resultType}> {`,
		);
		blocks.push(body);
		blocks.push("}");
		blocks.push("");
	}

	return blocks.join("\n");
}
