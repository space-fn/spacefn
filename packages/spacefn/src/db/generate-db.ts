import { columnType, paramsType, pascal } from "./generate-queries";
import type { GeneratedQuery } from "./generate-queries";
import type { Migration } from "./migrate";

/** Source of `.space/db/<name>.ts`: migrations and typed queries for one database. */
export function generateDbSource(
	name: string,
	migrations: Migration[],
	queries: GeneratedQuery[],
): string {
	const blocks: string[] = [];

	blocks.push("// Generated by space. Do not edit.");
	blocks.push(
		'import { queryD1, type D1Reader, type Migration, type SqlValue } from "spacefn/db";',
	);
	blocks.push("");

	blocks.push("export const migrations: Migration[] = [");
	for (const migration of migrations) {
		blocks.push(
			`\t{ id: ${JSON.stringify(migration.id)}, sql: ${JSON.stringify(migration.sql)} },`,
		);
	}
	blocks.push("];");
	blocks.push("");

	for (const query of queries) {
		const row = `${pascal(query.name)}Row`;
		const hasRows = query.mode !== "exec";
		if (hasRows && query.columns.length > 0) {
			blocks.push(`export interface ${row} {`);
			for (const column of query.columns) {
				blocks.push(`\t${column.name}: ${columnType(column)};`);
			}
			blocks.push("}");
			blocks.push("");
		}
		const paramType = paramsType(query);
		const values = query.paramNames.map((name) => `params.${name}`).join(", ");
		const resultType = hasRows
			? query.mode === "many"
				? `${row}[]`
				: `${row} | undefined`
			: "void";
		const body =
			query.mode === "exec"
				? `\tawait queryD1(db, ${JSON.stringify(query.boundSql)}, [${values}]);`
				: query.mode === "one"
					? `\treturn (await queryD1<${row}>(db, ${JSON.stringify(query.boundSql)}, [${values}]))[0];`
					: `\treturn queryD1<${row}>(db, ${JSON.stringify(query.boundSql)}, [${values}]);`;
		blocks.push(`/** ${query.sql.replace(/\*\//g, "* /")} */`);
		blocks.push(
			`export async function ${query.name}(db: D1Reader, params: ${paramType}): Promise<${resultType}> {`,
		);
		blocks.push(body);
		blocks.push("}");
		blocks.push("");
	}

	return blocks.join("\n");
}
