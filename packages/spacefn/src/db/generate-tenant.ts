import { paramsType, pascal, RESULT, columnType, type GeneratedQuery } from "./generate-queries";
import type { Migration } from "./migrate";

/** Method names a Durable Object already has, which a query may not shadow. */
const RESERVED = new Set([
	"constructor",
	"fetch",
	"alarm",
	"webSocketMessage",
	"webSocketClose",
	"webSocketError",
	"ctx",
	"env",
]);

/**
 * Source of `.space/tenant.ts`: the `Tenant` Durable Object. It applies the tenant
 * migrations before it serves anything, and each tenant query becomes a method.
 */
export function generateTenantSource(queries: GeneratedQuery[], migrations: Migration[]): string {
	const rows = queries
		.filter((query) => query.mode !== "exec")
		.map((query) => {
			const row = `${pascal(query.name)}Row`;
			return [
				`export interface ${row} {`,
				...query.columns.map((column) => `\t${column.name}: ${columnType(column)};`),
				"}",
				"",
			].join("\n");
		});

	const methods = queries.map((query) => {
		if (RESERVED.has(query.name))
			throw new Error(`Query name ${query.name} clashes with a Durable Object method`);
		const row = `${pascal(query.name)}Row`;
		const values = query.paramNames.map((name) => `params.${name}`).join(", ");
		const sql = JSON.stringify(query.boundSql);
		const call = `queryTenant<${row}>(this.ctx.storage, ${sql}, [${values}])`;
		const resultType = query.mode === "exec" ? "void" : RESULT(query.mode, row);
		const body =
			query.mode === "exec"
				? `\t\t${call};`
				: query.mode === "one"
					? `\t\treturn ${call}[0];`
					: `\t\treturn ${call};`;
		return [
			`\t/** ${query.sql.replace(/\*\//g, "* /")} */`,
			`\tasync ${query.name}(params: ${paramsType(query)}): Promise<${resultType}> {`,
			body,
			"\t}",
			"",
		].join("\n");
	});

	return [
		"// Generated by space. Do not edit.",
		'import { DurableObject } from "cloudflare:workers";',
		'import { migrateTenant, queryTenant, type Migration } from "spacefn/tenancy";',
		"",
		...rows,
		"const migrations: Migration[] = [",
		...migrations.map((m) => `\t{ id: ${JSON.stringify(m.id)}, sql: ${JSON.stringify(m.sql)} },`),
		"];",
		"",
		"export class Tenant extends DurableObject {",
		"\tconstructor(ctx: DurableObjectState, env: unknown) {",
		"\t\tsuper(ctx, env);",
		"\t\tctx.blockConcurrencyWhile(() => migrateTenant(ctx.storage, migrations));",
		"\t}",
		"",
		...methods,
		"}",
		"",
	].join("\n");
}
