export interface WorkerSourceOptions {
	/** Files in `middleware/`, already in run order, e.g. `["01-auth.ts"]`. */
	middleware?: string[];
	/** Files in `queues/`, e.g. `["emails.ts"]`. Each is a consumer named after the file. */
	queues?: string[];
	/** Files in `crons/`. Each is a scheduled job named after the file. */
	crons?: string[];
	/** Files in `durable-objects/`. Each exports a class extending DurableObject. */
	durableObjects?: string[];
	/** Files in `workflows/`. Each exports a class extending WorkflowEntrypoint. */
	workflows?: string[];
}

function stripExtension(file: string): string {
	return file.replace(/\.(?:[cm]?[jt]s|[jt]sx)$/, "");
}

/** Source of `.space/worker.ts`, the helper module imported by `app/entry.ts`. */
export function generateWorkerSource({
	middleware = [],
	queues = [],
	crons = [],
}: WorkerSourceOptions = {}): string {
	const runtime = [
		"Hono",
		"runWithBindings",
		"traceBindings",
		"traceConfig",
		"traceRequest",
		"envMiddleware",
		"type Schema",
		...(queues.length > 0 ? ["dispatchQueue", "type QueueBatch"] : []),
		...(crons.length > 0 ? ["dispatchScheduled"] : []),
	];

	const lines: string[] = [];
	lines.push("// Generated by space. Do not edit.");
	lines.push(`import { ${runtime.join(", ")} } from "spacefn/runtime";`);
	lines.push('import { registerRoutes as _registerRoutes } from "./routes";');
	for (const file of middleware) {
		const i = middleware.indexOf(file);
		lines.push(`import middleware${i} from "../app/middleware/${stripExtension(file)}";`);
	}
	for (const [i, file] of queues.entries()) {
		lines.push(`import queue${i} from "../app/queues/${stripExtension(file)}";`);
	}
	for (const [i, file] of crons.entries()) {
		lines.push(`import cron${i} from "../app/crons/${stripExtension(file)}";`);
	}
	lines.push("");

	// createApp
	lines.push("export function createApp(options?: { env?: Schema }) {");
	lines.push("\tconst app = new Hono();");
	lines.push("\tapp.use(traceConfig());");
	lines.push("\tapp.use(traceRequest());");
	lines.push("\tif (options?.env) app.use(envMiddleware(options.env));");
	for (const [i] of middleware.entries()) {
		lines.push(`\tapp.use(middleware${i});`);
	}
	lines.push("\treturn app;");
	lines.push("}");
	lines.push("");

	// registerRoutes
	lines.push("export function registerRoutes(app: Parameters<typeof _registerRoutes>[0]) {");
	lines.push("\t_registerRoutes(app);");
	lines.push("}");
	lines.push("");

	// mountApp
	lines.push("export function mountApp(app: { fetch: (...a: any[]) => any }) {");
	lines.push("\treturn {");
	lines.push("\t\tfetch: (request: Request, env: unknown, ctx: ExecutionContext) => {");
	lines.push("\t\t\tconst bindings = traceBindings(env as object);");
	lines.push("\t\t\treturn runWithBindings(bindings, () => app.fetch(request, bindings, ctx));");
	lines.push("\t\t},");
	if (queues.length > 0) {
		const handlers = queues.map(
			(file, i) => `\t\t\t${JSON.stringify(stripExtension(file))}: queue${i},`,
		);
		lines.push("\t\tqueue: (batch: QueueBatch<unknown>, env: unknown, ctx: ExecutionContext) =>");
		lines.push("\t\t\tdispatchQueue(batch, env as object, ctx, {");
		lines.push(...handlers.map((h) => `\t${h}`));
		lines.push("\t\t\t}),");
	}
	if (crons.length > 0) {
		const jobs = crons.map((file, i) => `\t\t\t${JSON.stringify(stripExtension(file))}: cron${i},`);
		lines.push(
			"\t\tscheduled: (controller: ScheduledController, env: unknown, ctx: ExecutionContext) =>",
		);
		lines.push(
			"\t\t\tdispatchScheduled({ cron: controller.cron, scheduledTime: controller.scheduledTime }, env as object, ctx, {",
		);
		lines.push(...jobs.map((j) => `\t${j}`));
		lines.push("\t\t\t}),");
	}
	lines.push("\t};");
	lines.push("}");

	return lines.join("\n");
}

/** Source of `.space/exports.ts` — re-exports of DOs and workflows. */
export function generateExportsSource(
	options: {
		durableObjects?: string[];
		workflows?: string[];
	} = {},
): string {
	const lines: string[] = ["// Generated by space. Do not edit."];
	for (const file of options.durableObjects ?? []) {
		const name = file
			.replace(/\.(?:[cm]?[jt]s|[jt]sx)$/, "")
			.split(/[-_]/)
			.filter(Boolean)
			.map((p) => p.charAt(0).toUpperCase() + p.slice(1))
			.join("");
		lines.push(
			`export { ${name} } from "../app/durable-objects/${file.replace(/\.(?:[cm]?[jt]s|[jt]sx)$/, "")}";`,
		);
	}
	for (const file of options.workflows ?? []) {
		const name = file
			.replace(/\.(?:[cm]?[jt]s|[jt]sx)$/, "")
			.split(/[-_]/)
			.filter(Boolean)
			.map((p) => p.charAt(0).toUpperCase() + p.slice(1))
			.join("");
		lines.push(
			`export { ${name} } from "../app/workflows/${file.replace(/\.(?:[cm]?[jt]s|[jt]sx)$/, "")}";`,
		);
	}
	if (lines.length === 1) lines.push("// (no durable objects or workflows)");
	return lines.join("\n");
}
