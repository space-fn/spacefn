export interface WorkerSourceOptions {
	/** The project has an `env.ts` to validate on each request. */
	hasEnv?: boolean;
	/** Files in `middleware/`, already in run order, e.g. `["01-auth.ts"]`. */
	middleware?: string[];
	/** Files in `queues/`, e.g. `["emails.ts"]`. Each is a consumer named after the file. */
	queues?: string[];
	/** Files in `crons/`. Each is a scheduled job named after the file. */
	crons?: string[];
}

function stripExtension(file: string): string {
	return file.replace(/\.(?:[cm]?[jt]s|[jt]sx)$/, "");
}

/** Source of `.space/worker.ts`, the Worker entry that serves the generated routes. */
export function generateWorkerSource({
	hasEnv = false,
	middleware = [],
	queues = [],
	crons = [],
}: WorkerSourceOptions = {}): string {
	const runtime = [
		"Hono",
		"runWithBindings",
		"traceBindings",
		"traceConfig",
		"traceRequest",
		...(hasEnv ? ["envMiddleware"] : []),
		...(queues.length > 0 ? ["dispatchQueue", "type QueueBatch"] : []),
		...(crons.length > 0 ? ["dispatchScheduled"] : []),
	];
	const handlers = queues.map(
		(file, i) => `\t\t${JSON.stringify(stripExtension(file))}: queue${i},`,
	);
	const jobs = crons.map((file, i) => `\t\t${JSON.stringify(stripExtension(file))}: cron${i},`);
	return [
		"// Generated by space. Do not edit.",
		`import { ${runtime.join(", ")} } from "spacefn/runtime";`,
		...(hasEnv ? ['import schema from "../env";'] : []),
		...middleware.map(
			(file, i) => `import middleware${i} from "../middleware/${stripExtension(file)}";`,
		),
		...queues.map((file, i) => `import queue${i} from "../queues/${stripExtension(file)}";`),
		...crons.map((file, i) => `import cron${i} from "../crons/${stripExtension(file)}";`),
		'import { registerRoutes } from "./routes";',
		"",
		"const app = new Hono();",
		"app.use(traceConfig());",
		"app.use(traceRequest());",
		...(hasEnv ? ["app.use(envMiddleware(schema));"] : []),
		...middleware.map((_, i) => `app.use(middleware${i});`),
		"registerRoutes(app);",
		"",
		"export default {",
		"\tfetch: (request: Request, env: object, ctx: ExecutionContext) => {",
		"\t\tconst bindings = traceBindings(env);",
		"\t\treturn runWithBindings(bindings, () => app.fetch(request, bindings, ctx));",
		"\t},",
		...(queues.length > 0
			? [
					"\tqueue: (batch: QueueBatch<unknown>, env: object, ctx: ExecutionContext) =>",
					"\t\tdispatchQueue(batch, env, ctx, {",
					...handlers,
					"\t\t}),",
				]
			: []),
		...(crons.length > 0
			? [
					"\tscheduled: (controller: ScheduledController, env: object, ctx: ExecutionContext) =>",
					"\t\tdispatchScheduled({ cron: controller.cron, scheduledTime: controller.scheduledTime }, env, ctx, {",
					...jobs,
					"\t\t}),",
				]
			: []),
		"};",
		"",
	].join("\n");
}
