import { SpaceError } from "../errors";
import { baseName } from "../scan";
import { queueBinding } from "./binding";

const IDENTIFIER = /^[A-Za-z_$][\w$]*$/;

/** `order-jobs` becomes `orderJobs`. */
export function producerName(file: string): string {
	const name = baseName(file).replace(/[-_.]+([a-zA-Z0-9])/g, (_, c: string) => c.toUpperCase());
	if (!IDENTIFIER.test(name)) {
		throw new SpaceError("QUEUE_BAD_NAME", `queues/${file} cannot be turned into a producer name`, {
			hint: "Use letters, digits and dashes.",
		});
	}
	return name;
}

/** Source of `.space/queues.ts`: one typed producer per `queues/` file. */
export function generateQueuesSource(files: string[]): string {
	const imports = files.map(
		(file, i) => `import type handler${i} from "../app/queues/${baseName(file)}";`,
	);
	const producers = files.map(
		(file, i) =>
			`\t${producerName(file)}: queueProducer<QueueBodyOf<typeof handler${i}>>(${JSON.stringify(queueBinding(file))}),`,
	);
	return [
		"// Generated by space. Do not edit.",
		'import { queueProducer, type QueueBodyOf } from "spacefn/queues";',
		...imports,
		"",
		"export const queues = {",
		...producers,
		"} as const;",
		"",
	].join("\n");
}
