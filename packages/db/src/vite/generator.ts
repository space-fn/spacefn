// --- Code Generator -----------------------------------------------------------
// Generates types.ts and migration files from schema definitions

import type { ColumnDefinition, TableDefinition } from "../types.js";
import type { SchemaChange } from "./differ.js";
import type { Dialect } from "./sql.js";
import {
	generateCreateTable,
	generateDropTable,
	generateAddColumn,
	generateDropColumn,
	generateAlterColumnNullability,
	generateAlterColumnDefault,
	generateAlterColumnType,
} from "./sql.js";

// --- Types.ts Generation -----------------------------------------------------

/** Map a ColumnDefinition to its TypeScript type */
function columnToTsType(col: ColumnDefinition): string {
	switch (col.dataType) {
		case "serial":
		case "integer":
			return "number";
		case "boolean":
			return "boolean";
		case "timestamp":
			return "Date";
		case "json":
			return "unknown";
		case "enum":
			if (col.enumValues) {
				return col.enumValues.map((v) => `"${v}"`).join(" | ");
			}
			return "string";
		case "text":
		case "varchar":
		default:
			return "string";
	}
}

/** Generate types.ts content */
export function generateTypesCode(tables: Record<string, TableDefinition>): string {
	const lines: string[] = [
		"// Generated by @spacefn/db — do not edit",
		"",
		'import type { Generated, TimestampColumnType } from "kysely"',
		"",
	];

	for (const [name, table] of Object.entries(tables)) {
		const rowName = `${name.charAt(0).toUpperCase()}${name.slice(1)}Row`;

		lines.push(`export type ${rowName} = {`);

		for (const [colName, col] of Object.entries(table.columns)) {
			const tsType = columnToTsType(col);
			const nullable = col.nullable ? " | null" : "";

			if (col.dataType === "serial") {
				lines.push(`  ${colName}: Generated<${tsType}>`);
			} else if (col.dataType === "timestamp" && col.default === "auto") {
				lines.push(`  ${colName}: Generated<TimestampColumnType>`);
			} else {
				lines.push(`  ${colName}: ${tsType}${nullable}`);
			}
		}

		lines.push("}");
		lines.push("");
	}

	// Database interface
	lines.push("export interface Database {");
	for (const name of Object.keys(tables)) {
		const rowName = `${name.charAt(0).toUpperCase()}${name.slice(1)}Row`;
		lines.push(`  ${name}: ${rowName}`);
	}
	lines.push("}");
	lines.push("");

	return lines.join("\n");
}

// --- Migration File Generation -----------------------------------------------

/** Generate timestamp prefix (YYYYMMDDHHMMSS) */
function timestamp(): string {
	const now = new Date();
	const pad = (n: number) => String(n).padStart(2, "0");
	return (
		String(now.getFullYear()) +
		pad(now.getMonth() + 1) +
		pad(now.getDate()) +
		pad(now.getHours()) +
		pad(now.getMinutes()) +
		pad(now.getSeconds())
	);
}

/** Generate a descriptive slug from schema changes */
function migrationSlug(changes: SchemaChange[]): string {
	const parts: string[] = [];

	for (const change of changes) {
		switch (change.type) {
			case "table_added":
				parts.push(`create_${change.table}`);
				break;
			case "table_dropped":
				parts.push(`drop_${change.table}`);
				break;
			case "column_added":
				parts.push(`add_${change.column}_to_${change.table}`);
				break;
			case "column_dropped":
				parts.push(`drop_${change.column}_from_${change.table}`);
				break;
			case "column_changed":
				parts.push(`change_${change.column}_on_${change.table}`);
				break;
		}
	}

	return parts.join("_") || "migration";
}

/** Generate a single migration file content */
export function generateMigrationFile(
	changes: SchemaChange[],
	dialect: Dialect,
): { name: string; content: string } {
	const ts = timestamp();
	const slug = migrationSlug(changes);
	const name = `${ts}_${slug}`;

	const upSql: string[] = [];
	const downSql: string[] = [];

	for (const change of changes) {
		switch (change.type) {
			case "table_added":
				upSql.push(generateCreateTable(change.definition, dialect));
				downSql.push(generateDropTable(change.table, dialect));
				break;
			case "table_dropped":
				// For drop, we'd need the old definition to generate down
				// Store a comment for now
				downSql.push(`-- Cannot reverse DROP TABLE ${change.table} without previous schema`);
				break;
			case "column_added":
				upSql.push(generateAddColumn(change.table, change.column, change.definition, dialect));
				downSql.push(generateDropColumn(change.table, change.column, dialect));
				break;
			case "column_dropped":
				downSql.push(`-- Cannot reverse DROP COLUMN ${change.column} without previous schema`);
				break;
			case "column_changed":
				// Generate individual ALTER statements for each changed property
				if (change.before.dataType !== change.after.dataType) {
					upSql.push(generateAlterColumnType(change.table, change.column, change.after, dialect));
				}
				if (change.before.nullable !== change.after.nullable) {
					upSql.push(
						generateAlterColumnNullability(change.table, change.column, change.after, dialect),
					);
				}
				if (change.before.default !== change.after.default) {
					upSql.push(
						generateAlterColumnDefault(change.table, change.column, change.after, dialect),
					);
				}
				// Reverse changes for down
				if (change.after.dataType !== change.before.dataType) {
					downSql.push(
						generateAlterColumnType(change.table, change.column, change.before, dialect),
					);
				}
				if (change.after.nullable !== change.before.nullable) {
					downSql.push(
						generateAlterColumnNullability(change.table, change.column, change.before, dialect),
					);
				}
				if (change.after.default !== change.before.default) {
					downSql.push(
						generateAlterColumnDefault(change.table, change.column, change.before, dialect),
					);
				}
				break;
		}
	}

	const content = [
		'import type { Kysely } from "kysely"',
		'import { sql } from "kysely"',
		"",
		"export async function up(db: Kysely<any>): Promise<void> {",
		...upSql.map((s) => `  await sql\`${s}\`.execute(db)`),
		"}",
		"",
		"export async function down(db: Kysely<any>): Promise<void> {",
		...downSql.map((s) => `  await sql\`${s}\`.execute(db)`),
		"}",
		"",
	].join("\n");

	return { name, content };
}

// --- Migration Index Generation ----------------------------------------------

/** Generate migrations/index.ts barrel file */
export function generateMigrationIndex(migrationFiles: string[], _dialect: Dialect): string {
	const imports: string[] = [];
	const entries: string[] = [];

	for (const file of migrationFiles) {
		// Extract name from path (e.g., "20240315120000_initial" from "./20240315120000_initial.ts")
		const match = file.match(/\/([^/]+)\.ts$/);
		if (!match) continue;
		const name = match[1];
		const varName = `m_${name.replace(/[^a-zA-Z0-9]/g, "_")}`;

		imports.push(`import * as ${varName} from "./${name}"`);
		entries.push(`  "${name}": ${varName}`);
	}

	return [
		"// Generated by @spacefn/db — do not edit",
		'import { Migrator } from "kysely"',
		"",
		...imports,
		"",
		"const migrations = {",
		...entries,
		"}",
		"",
		"export function createMigrator(db: any) {",
		"  return new Migrator({",
		"    db,",
		"    provider: {",
		"      async getMigrations() {",
		"        return migrations",
		"      },",
		"    },",
		"  })",
		"}",
		"",
	].join("\n");
}
