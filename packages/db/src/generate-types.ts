import { type ColumnDef } from "./column.js";
import { type SchemaDef, getColumns, toPascalCase } from "./schema-types.js";

function mapColumnType(col: ColumnDef): string {
	let type: string;
	switch (col.type) {
		case "text":
		case "json":
			type = "string";
			break;
		case "integer":
		case "real":
			type = "number";
			break;
		case "blob":
			type = "ArrayBuffer";
			break;
		default:
			type = "string";
	}

	if (col.autoIncrement || col.default !== undefined) {
		type = `Generated<${type}>`;
	}

	// Primary keys are never nullable
	if (!col.notNull && !col.primaryKey) {
		type = `${type} | null`;
	}

	return type;
}

export function generateTypes(schema: SchemaDef, hash?: string): string {
	const lines: string[] = [];

	lines.push(`// Auto-generated by db generators — DO NOT EDIT`);
	lines.push(`// schema-hash: ${hash ?? ""}`);
	lines.push(`import type { Generated, Selectable, Insertable, Updateable } from "kysely"`);
	lines.push("");

	for (const [tableName, tableDef] of Object.entries(schema)) {
		const columns = getColumns(tableDef);
		const typeName = toPascalCase(tableName);

		lines.push(`export type ${typeName} = {`);
		for (const [colName, colDef] of Object.entries(columns)) {
			lines.push(`  ${colName}: ${mapColumnType(colDef)}`);
		}
		lines.push(`}`);
		lines.push("");
		lines.push(`export type ${typeName}Select = Selectable<${typeName}>`);
		lines.push(`export type ${typeName}Insert = Insertable<${typeName}>`);
		lines.push(`export type ${typeName}Update = Updateable<${typeName}>`);
		lines.push("");
	}

	lines.push(`export type Database = {`);
	for (const tableName of Object.keys(schema)) {
		lines.push(`  ${tableName}: ${toPascalCase(tableName)}`);
	}
	lines.push(`}`);
	lines.push("");

	return lines.join("\n");
}
